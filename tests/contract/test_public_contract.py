"""Contract tests for the published public API (F021).

The snapshot ``docs/spec/public_contract.json`` is generated from the code by
``geneforgelang.public_contract``. These tests prove that a surface change without a version
bump and a changelog entry is rejected, that the release tag must agree with the package
metadata, and that every public function carries an evidence label.
"""

from __future__ import annotations

import copy
import functools
import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

from geneforgelang import public_contract as pc
from geneforgelang.core import api

ROOT = Path(__file__).resolve().parents[2]
SNAPSHOT = ROOT / pc.SNAPSHOT_PATH


@pytest.fixture(scope="module")
def baseline() -> dict:
    return json.loads(SNAPSHOT.read_text(encoding="utf-8"))


@pytest.fixture
def at_root(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.chdir(ROOT)


def _changelog(version: str) -> str:
    return f"## [Unreleased]\n- Contract {version}: change.\n"


def _bumped(contract: dict, version: str) -> dict:
    out = copy.deepcopy(contract)
    out["contract_version"] = version
    return out


# ---------------------------------------------------------------- D1: snapshot vs code


def test_snapshot_matches_the_code(baseline: dict) -> None:
    assert pc.build_contract(ROOT) == baseline


def test_snapshot_lists_the_public_surface(baseline: dict) -> None:
    assert sorted(baseline["functions"]) == sorted(api.__all__)
    assert "ErrorCodes" in baseline["classes"]
    assert baseline["contract_version"] == pc.CONTRACT_VERSION
    assert baseline["grammar_version"] == pc.GRAMMAR_VERSION
    assert baseline["generated"].startswith("Generated by")


def test_cli_check_passes_on_the_committed_snapshot() -> None:
    proc = subprocess.run(
        [sys.executable, "-m", "geneforgelang.public_contract", "--check"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert proc.stdout.startswith("OK")


def test_signature_change_makes_check_fail(
    monkeypatch: pytest.MonkeyPatch, at_root: None, capsys: pytest.CaptureFixture
) -> None:
    original = api.parse

    def parse(text: str, strict: bool = False, filename: str = "<input>"):
        return original(text, filename=filename)

    monkeypatch.setattr(api, "parse", parse)
    assert pc.main(["--check"]) == 1
    out = capsys.readouterr().out
    assert "function parse" in out and "'use_grammar'" in out


def test_parser_losing_a_construct_makes_check_fail(
    monkeypatch: pytest.MonkeyPatch, at_root: None, capsys: pytest.CaptureFixture
) -> None:
    original = api.parse

    @functools.wraps(original)
    def parse(*args, **kwargs):
        if str(args[0]).startswith("timeline:"):
            raise ValueError("construct dropped")
        return original(*args, **kwargs)

    monkeypatch.setattr(api, "parse", parse)
    assert pc.main(["--check"]) == 1
    out = capsys.readouterr().out
    assert "grammar construct 'timeline' is no longer parsed" in out


# ----------------------------------------- D2: version bump and changelog rules (compare)


def test_identical_contracts_are_accepted(baseline: dict) -> None:
    assert pc.compare(baseline, baseline, "") == []


def test_removed_function_without_bump_fails(baseline: dict) -> None:
    current = copy.deepcopy(baseline)
    del current["functions"]["get_api_info"]
    problems = pc.compare(baseline, current, _changelog(current["contract_version"]))
    assert len(problems) == 1
    assert "function get_api_info removed" in problems[0] and "MAJOR" in problems[0]


def test_removed_function_with_minor_bump_still_fails(baseline: dict) -> None:
    current = _bumped(baseline, "1.1.0")
    del current["functions"]["get_api_info"]
    assert any("MAJOR" in p for p in pc.compare(baseline, current, _changelog("1.1.0")))


def test_removed_function_with_major_bump_needs_a_changelog_entry(baseline: dict) -> None:
    current = _bumped(baseline, "2.0.0")
    del current["functions"]["get_api_info"]
    problems = pc.compare(baseline, current, "## [Unreleased]\n")
    assert problems == ["CHANGELOG has no 'Contract 2.0.0' entry for the change"]
    assert pc.compare(baseline, current, _changelog("2.0.0")) == []


def test_changelog_entry_for_another_version_does_not_count(baseline: dict) -> None:
    current = _bumped(baseline, "2.0.0")
    del current["functions"]["get_api_info"]
    assert pc.compare(baseline, current, _changelog("2.0.1"))


def test_added_function_needs_a_minor_bump(baseline: dict) -> None:
    current = copy.deepcopy(baseline)
    current["functions"]["new_one"] = copy.deepcopy(baseline["functions"]["parse"])
    patch = _bumped(current, "1.0.1")
    assert any("MINOR" in p for p in pc.compare(baseline, patch, _changelog("1.0.1")))
    minor = _bumped(current, "1.1.0")
    assert pc.compare(baseline, minor, _changelog("1.1.0")) == []


def test_renamed_parameter_is_breaking(baseline: dict) -> None:
    current = copy.deepcopy(baseline)
    current["functions"]["parse"]["signature"]["parameters"][0]["name"] = "source"
    changes = pc.diff_surface(baseline, current)
    assert changes and all(kind == "breaking" for kind, _ in changes)


def test_new_required_parameter_is_breaking_and_optional_is_additive(baseline: dict) -> None:
    param = {
        "name": "x",
        "kind": "POSITIONAL_OR_KEYWORD",
        "annotation": None,
        "default": None,
        "required": True,
    }
    current = copy.deepcopy(baseline)
    current["functions"]["parse"]["signature"]["parameters"].append(param)
    assert pc.diff_surface(baseline, current)[0][0] == "breaking"
    param.update(required=False, default="None")
    assert pc.diff_surface(baseline, current)[0][0] == "additive"


def test_removed_error_code_is_breaking(baseline: dict) -> None:
    current = copy.deepcopy(baseline)
    members = current["classes"]["ErrorCodes"]["members"]
    removed = sorted(members)[0]
    del members[removed]
    changes = pc.diff_surface(baseline, current)
    assert ("breaking", f"class ErrorCodes.{removed} removed") in changes


def test_changed_error_code_value_is_breaking(baseline: dict) -> None:
    current = copy.deepcopy(baseline)
    members = current["classes"]["ErrorCodes"]["members"]
    name = sorted(members)[0]
    members[name]["value"] = "CHANGED"
    assert pc.diff_surface(baseline, current)[0][0] == "breaking"


def test_lowering_an_evidence_label_is_breaking_and_raising_is_additive(
    baseline: dict,
) -> None:
    lowered = copy.deepcopy(baseline)
    lowered["functions"]["parse"]["evidence"]["label"] = "simulated"
    assert pc.diff_surface(baseline, lowered)[0][0] == "breaking"
    raised = copy.deepcopy(baseline)
    raised["functions"]["execute"]["evidence"]["label"] = "computed"
    assert pc.diff_surface(baseline, raised)[0][0] == "additive"


def test_removed_grammar_construct_is_breaking_and_added_is_additive(baseline: dict) -> None:
    removed = copy.deepcopy(baseline)
    removed["grammar"]["constructs"]["timeline"] = False
    assert ("breaking", "grammar construct 'timeline' is no longer parsed") in pc.diff_surface(
        baseline, removed
    )
    added = copy.deepcopy(baseline)
    added["grammar"]["constructs"]["loci"] = True
    assert ("additive", "grammar construct 'loci' is now parsed") in pc.diff_surface(
        baseline, added
    )


def test_grammar_version_bump_forces_a_contract_bump(baseline: dict) -> None:
    current = copy.deepcopy(baseline)
    current["grammar_version"] = "1.3.0"
    problems = pc.compare(baseline, current, _changelog(current["contract_version"]))
    assert any("MINOR" in p for p in problems)
    current["contract_version"] = "1.1.0"
    assert pc.compare(baseline, current, _changelog("1.1.0")) == []


def test_versions_cannot_go_backwards(baseline: dict) -> None:
    current = _bumped(baseline, "0.9.0")
    assert any("went back" in p for p in pc.compare(baseline, current, ""))
    current = copy.deepcopy(baseline)
    current["grammar_version"] = "1.1.0"
    assert any("grammar_version went back" in p for p in pc.compare(baseline, current, ""))


# ------------------------------------------- D2: the same rules through git and the CLI


def _git(cwd: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True)


def _against(repo: Path, ref: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "geneforgelang.public_contract", "--against", ref],
        cwd=repo,
        capture_output=True,
        text=True,
        check=False,
    )


@pytest.fixture
def repo(tmp_path: Path, baseline: dict) -> Path:
    _git(tmp_path, "init", "-q")
    _git(tmp_path, "config", "user.email", "test@example.invalid")
    _git(tmp_path, "config", "user.name", "test")
    (tmp_path / "docs" / "spec").mkdir(parents=True)
    (tmp_path / "docs/spec/public_contract.json").write_text(pc.render(baseline), encoding="utf-8")
    (tmp_path / "CHANGELOG.md").write_text("# Changelog\n", encoding="utf-8")
    _git(tmp_path, "add", ".")
    _git(tmp_path, "commit", "-qm", "baseline")
    return tmp_path


def _commit_snapshot(repo: Path, contract: dict, changelog: str | None = None) -> None:
    (repo / "docs/spec/public_contract.json").write_text(pc.render(contract), encoding="utf-8")
    if changelog is not None:
        (repo / "CHANGELOG.md").write_text(changelog, encoding="utf-8")
    _git(repo, "add", ".")
    _git(repo, "commit", "-qm", "change")


def test_against_rejects_a_removal_without_bump(repo: Path, baseline: dict) -> None:
    mutated = copy.deepcopy(baseline)
    del mutated["functions"]["infer"]
    _commit_snapshot(repo, mutated)
    proc = _against(repo, "HEAD~1")
    assert proc.returncode != 0
    assert "function infer removed" in proc.stdout


def test_against_accepts_a_removal_with_major_bump_and_changelog(
    repo: Path, baseline: dict
) -> None:
    mutated = _bumped(baseline, "2.0.0")
    del mutated["functions"]["infer"]
    _commit_snapshot(repo, mutated, _changelog("2.0.0"))
    proc = _against(repo, "HEAD~1")
    assert proc.returncode == 0, proc.stdout
    assert proc.stdout.startswith("OK")


def test_against_tolerates_a_ref_without_a_snapshot(repo: Path) -> None:
    assert _against(repo, "HEAD").returncode == 0  # same commit: nothing changed
    _git(repo, "rm", "-q", "docs/spec/public_contract.json")
    _git(repo, "commit", "-qm", "drop")
    (repo / "docs/spec").mkdir(parents=True, exist_ok=True)
    (repo / "docs/spec/public_contract.json").write_text("{}", encoding="utf-8")
    proc = _against(repo, "HEAD")
    assert proc.returncode == 0 and "NOTICE: no baseline snapshot" in proc.stdout


# ------------------------------------------------------------- D3: tag vs package metadata


def _pyproject(path: Path, version: str) -> Path:
    path.write_text(
        f'[build-system]\nrequires = []\n\n[project]\nname = "x"\nversion = "{version}"\n',
        encoding="utf-8",
    )
    return path


def test_tag_matching_the_metadata_passes(tmp_path: Path) -> None:
    pyproject = _pyproject(tmp_path / "pyproject.toml", "3.4.5")
    assert pc.check_tag("v3.4.5", pyproject, "3.4.5") == []


def test_tag_disagreeing_with_pyproject_or_package_version_fails(tmp_path: Path) -> None:
    pyproject = _pyproject(tmp_path / "pyproject.toml", "3.4.5")
    assert pc.check_tag("v9.9.9", pyproject, "9.9.9") == [
        "tag v9.9.9 != pyproject.toml version 3.4.5",
    ]
    assert pc.check_tag("v3.4.5", pyproject, "3.4.4") == [
        "tag v3.4.5 != geneforgelang.__version__ 3.4.4",
    ]
    assert len(pc.check_tag("v9.9.9", pyproject, "3.4.4")) == 2


@pytest.mark.parametrize("tag", ["1.0.0", "v1.0", "v2025.06-initial-stable", "v1.0.0-rc1"])
def test_non_release_tags_are_rejected(tag: str, tmp_path: Path) -> None:
    problems = pc.check_tag(tag, _pyproject(tmp_path / "pyproject.toml", "1.0.0"), "1.0.0")
    assert problems and "not a release tag" in problems[0]


def test_version_is_read_from_the_project_table_only(tmp_path: Path) -> None:
    path = tmp_path / "pyproject.toml"
    path.write_text('[tool.x]\nversion = "7.7.7"\n[project]\nversion = "1.2.3"\n', encoding="utf-8")
    assert pc.check_tag("v1.2.3", path, "1.2.3") == []


def test_cli_check_tag_uses_the_real_metadata() -> None:
    import geneforgelang

    real = pc._pyproject_version(ROOT / "pyproject.toml")
    run = functools.partial(
        subprocess.run,
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
        env={**os.environ, "PYTHONIOENCODING": "utf-8"},
    )
    cmd = [sys.executable, "-m", "geneforgelang.public_contract", "--check-tag"]
    assert run([*cmd, "v9.9.9"]).returncode == 1
    ok = run([*cmd, f"v{real}"])
    # The tag passes only when pyproject.toml and __version__ agree: they must not drift.
    assert (ok.returncode == 0) == (geneforgelang.__version__ == real), ok.stdout


def test_package_metadata_agrees() -> None:
    import geneforgelang

    assert geneforgelang.__version__ == pc._pyproject_version(ROOT / "pyproject.toml")


# ------------------------------------------------ D4: evidence labels on the public names


def test_every_public_name_has_a_valid_label() -> None:
    assert sorted(pc.EVIDENCE_LABELS) == sorted(api.__all__)
    assert {label for label, _ in pc.EVIDENCE_LABELS.values()} <= set(pc.EVIDENCE_ORDER)
    assert all(reason.strip() for _, reason in pc.EVIDENCE_LABELS.values())


def test_a_new_public_name_without_a_label_breaks_the_build(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setattr(api, "__all__", [*api.__all__, "brand_new"])
    monkeypatch.setattr(api, "brand_new", lambda: None, raising=False)
    with pytest.raises(pc.ContractError, match=r"missing=\['brand_new'\]"):
        pc.build_contract(ROOT)


def test_an_invalid_label_breaks_the_build(monkeypatch: pytest.MonkeyPatch) -> None:
    labels = {**pc.EVIDENCE_LABELS, "parse": ("validated", "no such label")}
    monkeypatch.setattr(pc, "EVIDENCE_LABELS", labels)
    with pytest.raises(pc.ContractError, match=r"invalid label=\['parse'\]"):
        pc.build_contract(ROOT)


def test_simulated_label_on_execute_matches_the_behaviour() -> None:
    """Two runs of the same design block give different sequences: the output is simulated."""
    from geneforgelang.plugins.plugin_registry import PluginRegistry
    from geneforgelang.utils.example_implementations import ProteinVAEGenerator

    registry = PluginRegistry()
    generator = ProteinVAEGenerator()
    registry.register("ProteinVAEGenerator", generator, "1.2.0")
    registry.register_generator("ProteinVAEGenerator", generator)
    ast = api.parse(
        "design:\n  entity: ProteinSequence\n  model: ProteinVAEGenerator\n"
        "  objective:\n    maximize: stability\n  count: 10\n  output: designed_proteins\n"
    )
    first = [c.sequence for c in api.execute(ast, registry)["design"]]
    second = [c.sequence for c in api.execute(ast, registry)["design"]]
    assert len(first) == len(second) == 10
    assert first != second
    assert pc.EVIDENCE_LABELS["execute"][0] == "simulated"


