"""Published contract of the GeneForgeLang public API.

Clients (GeneForge, PharmaOracle, third parties) rely on the surface described
here. The contract is *generated from the code*: ``build_contract()`` inspects
``geneforgelang.core.api`` and the error types, and ``docs/spec/public_contract.json``
is a committed snapshot of its output. Nothing in the snapshot is typed by hand.

A change to the surface is classified against a baseline as *breaking* or
*additive* by ``compare()``. It is accepted only with a matching bump of
``CONTRACT_VERSION`` (SemVer) and a ``Contract X.Y.Z`` line in the changelog.

Command line (run from the repository root)::

    python -m geneforgelang.public_contract --write          # regenerate the snapshot
    python -m geneforgelang.public_contract --check          # snapshot equals the code
    python -m geneforgelang.public_contract --against REF    # bump rules against a git ref
    python -m geneforgelang.public_contract --check-tag TAG  # tag equals package metadata
"""

from __future__ import annotations

import argparse
import contextlib
import dataclasses
import enum
import importlib
import inspect
import io
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

# SemVer of the client-visible surface. Bump it with every surface change (see compare()).
CONTRACT_VERSION = "1.0.0"

# Version of the language the parser and validator implement. v1.3.0 to v1.5.0 conformance
# directories describe constructs the validator does not implement yet (see "grammar").
GRAMMAR_VERSION = "1.2.0"

PUBLIC_MODULE = "geneforgelang.core.api"

# Weakest to strongest. Moving up is additive, moving down is breaking.
EVIDENCE_ORDER = ("stub", "simulated", "computed", "measured")

# Evidence label of the output of every public function, with the reason.
# build_contract() fails when a public name has no label.
EVIDENCE_LABELS: dict[str, tuple[str, str]] = {
    "parse": ("computed", "deterministic parsing of the input text"),
    "parse_enhanced": ("computed", "deterministic parsing with structured errors"),
    "validate": ("computed", "deterministic rule checks on the AST"),
    "validate_plugins": ("computed", "deterministic check of plugin requirements"),
    "list_available_plugins": ("computed", "lists the plugins discovered at call time"),
    "get_api_info": ("computed", "reports the contract versions and detected features"),
    "infer": (
        "simulated",
        "simulated unless the caller passes a measured model; the library ships none",
    ),
    "infer_enhanced": ("simulated", "heuristic rules and DummyGeneModel, not measured"),
    "compare_inference_models": ("simulated", "compares heuristic and dummy models"),
    "execute": (
        "simulated",
        "returns what the registered plugins return; every plugin shipped with the "
        "library generates random results",
    ),
}

# Classes clients may catch, construct or read. The module is imported lazily.
PUBLIC_CLASSES: dict[str, str] = {
    "EnhancedValidationError": "geneforgelang.core.errors",
    "EnhancedValidationResult": "geneforgelang.core.errors",
    "ErrorSeverity": "geneforgelang.core.errors",
    "ErrorCategory": "geneforgelang.core.errors",
    "ErrorCodes": "geneforgelang.core.errors",
    "GFLSyntaxError": "geneforgelang.utils.grammar_parser",
    "ExecutionError": "geneforgelang.core.execution",
}

# One minimal sample per top-level construct of the grammar. parse() must return the
# construct name as a key.
GRAMMAR_CONSTRUCT_SAMPLES: dict[str, str] = {
    name: f"{name}:\n  x: 1\n"
    for name in (
        "experiment",
        "design",
        "optimize",
        "rules",
        "hypothesis",
        "timeline",
        "pathways",
        "complexes",
    )
}

SNAPSHOT_PATH = Path("docs/spec/public_contract.json")
CHANGELOG_PATH = Path("CHANGELOG.md")
CONFORMANCE_DIR = Path("tests/conformance_suite")

_SNAPSHOT_HEADER = (
    "Generated by `python -m geneforgelang.public_contract --write`. Do not edit by hand."
)
_SEMVER = re.compile(r"^(\d+)\.(\d+)\.(\d+)$")
_BUMP_RANK = {"none": 0, "patch": 1, "minor": 2, "major": 3}


class ContractError(Exception):
    """The contract cannot be built or is internally inconsistent."""


# --------------------------------------------------------------------------- building


def _describe_signature(obj: Any) -> dict[str, Any]:
    """Return a JSON-able description of a callable's signature."""
    sig = inspect.signature(obj)
    params = []
    for p in sig.parameters.values():
        params.append(
            {
                "name": p.name,
                "kind": p.kind.name,
                "annotation": None if p.annotation is p.empty else str(p.annotation),
                "default": None if p.default is p.empty else repr(p.default),
                "required": p.default is p.empty
                and p.kind not in (p.VAR_POSITIONAL, p.VAR_KEYWORD),
            }
        )
    ret = None if sig.return_annotation is sig.empty else str(sig.return_annotation)
    return {"parameters": params, "return": ret}


def _describe_class(cls: type) -> dict[str, Any]:
    """Describe the public members of a class: constants, fields, methods, enum values."""
    members: dict[str, dict[str, Any]] = {}
    field_names: set[str] = set()
    if dataclasses.is_dataclass(cls):
        for f in dataclasses.fields(cls):
            field_names.add(f.name)
            required = (
                f.default is dataclasses.MISSING and f.default_factory is dataclasses.MISSING
            )
            members[f.name] = {"kind": "field", "type": str(f.type), "required": required}
    is_enum = issubclass(cls, enum.Enum)
    if is_enum:
        for m in cls:
            members[m.name] = {"kind": "enum_member", "value": m.value}
    for name, value in vars(cls).items():
        if name.startswith("_") or name in field_names or (is_enum and name in cls.__members__):
            continue
        raw = value.__func__ if isinstance(value, (staticmethod, classmethod)) else value
        if isinstance(raw, property):
            members[name] = {"kind": "property"}
        elif inspect.isfunction(raw):
            members[name] = {"kind": "method", "signature": _describe_signature(raw)}
        elif isinstance(raw, (str, int, float, bool)):
            members[name] = {"kind": "constant", "value": raw}
    return {
        "module": cls.__module__,
        "bases": [b.__name__ for b in cls.__bases__ if b is not object],
        "members": dict(sorted(members.items())),
    }


def _parse_quietly(text: str) -> Any:
    """Call the public parse() without letting its diagnostics reach stdout."""
    api = importlib.import_module(PUBLIC_MODULE)
    with contextlib.redirect_stdout(io.StringIO()):
        return api.parse(text)


def _parse_keys(text: str) -> list[str]:
    try:
        ast = _parse_quietly(text)
    except Exception as exc:  # noqa: BLE001 - any failure means the construct is not parsed
        return [f"!error:{type(exc).__name__}"]
    return sorted(ast) if isinstance(ast, dict) else ["!no-ast"]


def _suite_versions(root: Path) -> list[str]:
    base = root / CONFORMANCE_DIR
    if not base.is_dir():
        raise ContractError(f"conformance suite not found at {base}")
    found = [d.name[1:] for d in base.iterdir() if d.is_dir() and re.fullmatch(r"v\d+\.\d+\.\d+", d.name)]
    return sorted(found, key=_version_tuple)


def _version_tuple(version: str) -> tuple[int, int, int]:
    m = _SEMVER.match(version)
    if not m:
        raise ContractError(f"not a SemVer version: {version!r}")
    return int(m[1]), int(m[2]), int(m[3])


def _grammar_section(root: Path) -> dict[str, Any]:
    versions = _suite_versions(root)
    if GRAMMAR_VERSION not in versions:
        raise ContractError(
            f"GRAMMAR_VERSION {GRAMMAR_VERSION} has no directory v{GRAMMAR_VERSION} in "
            f"{root / CONFORMANCE_DIR}"
        )
    suite_dir = root / CONFORMANCE_DIR / f"v{GRAMMAR_VERSION}"
    samples = {}
    for path in sorted(suite_dir.rglob("*.gfl")):
        samples[path.relative_to(root).as_posix()] = _parse_keys(path.read_text(encoding="utf-8"))
    return {
        "constructs": {
            name: name in _parse_keys(sample)
            for name, sample in GRAMMAR_CONSTRUCT_SAMPLES.items()
        },
        "conformance_samples": samples,
        "unimplemented_suites": [
            v for v in versions if _version_tuple(v) > _version_tuple(GRAMMAR_VERSION)
        ],
    }


def build_contract(root: Path | None = None) -> dict[str, Any]:
    """Build the contract from the code. ``root`` is the repository root (default: cwd)."""
    root = root or Path.cwd()
    api = importlib.import_module(PUBLIC_MODULE)
    public = list(api.__all__)

    unlabelled = [n for n in public if n not in EVIDENCE_LABELS]
    stale = [n for n in EVIDENCE_LABELS if n not in public]
    bad = [n for n, (label, _) in EVIDENCE_LABELS.items() if label not in EVIDENCE_ORDER]
    if unlabelled or stale or bad:
        raise ContractError(
            "evidence labels out of sync with the public names: "
            f"missing={unlabelled}, unknown={stale}, invalid label={bad}"
        )

    functions = {}
    for name in sorted(public):
        label, reason = EVIDENCE_LABELS[name]
        functions[name] = {
            "signature": _describe_signature(getattr(api, name)),
            "evidence": {"label": label, "reason": reason},
        }
    classes = {}
    for name, module in sorted(PUBLIC_CLASSES.items()):
        classes[name] = _describe_class(getattr(importlib.import_module(module), name))

    return {
        "generated": _SNAPSHOT_HEADER,
        "contract_version": CONTRACT_VERSION,
        "grammar_version": GRAMMAR_VERSION,
        "module": PUBLIC_MODULE,
        "functions": functions,
        "classes": classes,
        "grammar": _grammar_section(root),
    }


def render(contract: dict[str, Any]) -> str:
    return json.dumps(contract, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


# ------------------------------------------------------------------------- comparing


def _diff_signature(where: str, old: dict[str, Any], new: dict[str, Any]) -> list[tuple[str, str]]:
    changes: list[tuple[str, str]] = []
    old_params, new_params = old["parameters"], new["parameters"]
    for i, op in enumerate(old_params):
        if i >= len(new_params):
            changes.append(("breaking", f"{where}: parameter '{op['name']}' removed"))
            continue
        np_ = new_params[i]
        if np_["name"] != op["name"] or np_["kind"] != op["kind"]:
            changes.append(
                ("breaking", f"{where}: parameter {i} changed from '{op['name']}' ({op['kind']}) "
                 f"to '{np_['name']}' ({np_['kind']})")
            )
        elif np_["default"] != op["default"]:
            changes.append(
                ("breaking", f"{where}: default of '{op['name']}' changed from "
                 f"{op['default']} to {np_['default']}")
            )
        elif np_["annotation"] != op["annotation"]:
            changes.append(
                ("breaking", f"{where}: annotation of '{op['name']}' changed from "
                 f"{op['annotation']} to {np_['annotation']}")
            )
    for np_ in new_params[len(old_params):]:
        kind = "breaking" if np_["required"] else "additive"
        changes.append((kind, f"{where}: parameter '{np_['name']}' added"
                        + (" (required)" if np_["required"] else "")))
    if old["return"] != new["return"]:
        changes.append(("breaking", f"{where}: return annotation changed from "
                        f"{old['return']} to {new['return']}"))
    return changes


def _diff_class(name: str, old: dict[str, Any], new: dict[str, Any]) -> list[tuple[str, str]]:
    changes: list[tuple[str, str]] = []
    if old["bases"] != new["bases"]:
        changes.append(("breaking", f"class {name}: bases changed from {old['bases']} to {new['bases']}"))
    for member, om in old["members"].items():
        nm = new["members"].get(member)
        where = f"class {name}.{member}"
        if nm is None:
            changes.append(("breaking", f"{where} removed"))
        elif om["kind"] != nm["kind"]:
            changes.append(("breaking", f"{where} changed kind from {om['kind']} to {nm['kind']}"))
        elif om["kind"] == "method":
            changes.extend(_diff_signature(where, om["signature"], nm["signature"]))
        elif om != nm:
            changes.append(("breaking", f"{where} changed from {om} to {nm}"))
    for member, nm in new["members"].items():
        if member not in old["members"]:
            kind = "breaking" if nm.get("required") else "additive"
            changes.append((kind, f"class {name}.{member} added"))
    return changes


def diff_surface(old: dict[str, Any], new: dict[str, Any]) -> list[tuple[str, str]]:
    """Classify every difference between two contracts as ``breaking`` or ``additive``."""
    changes: list[tuple[str, str]] = []

    for name, of in old["functions"].items():
        nf = new["functions"].get(name)
        if nf is None:
            changes.append(("breaking", f"function {name} removed"))
            continue
        changes.extend(_diff_signature(f"function {name}", of["signature"], nf["signature"]))
        old_rank = EVIDENCE_ORDER.index(of["evidence"]["label"])
        new_rank = EVIDENCE_ORDER.index(nf["evidence"]["label"])
        if new_rank < old_rank:
            changes.append(("breaking", f"function {name}: evidence label lowered from "
                            f"{of['evidence']['label']} to {nf['evidence']['label']}"))
        elif new_rank > old_rank:
            changes.append(("additive", f"function {name}: evidence label raised from "
                            f"{of['evidence']['label']} to {nf['evidence']['label']}"))
    for name in new["functions"]:
        if name not in old["functions"]:
            changes.append(("additive", f"function {name} added"))

    for name, oc in old["classes"].items():
        nc = new["classes"].get(name)
        if nc is None:
            changes.append(("breaking", f"class {name} removed"))
        else:
            changes.extend(_diff_class(name, oc, nc))
    for name in new["classes"]:
        if name not in old["classes"]:
            changes.append(("additive", f"class {name} added"))

    og, ng = old["grammar"], new["grammar"]
    for name, supported in og["constructs"].items():
        if supported and not ng["constructs"].get(name, False):
            changes.append(("breaking", f"grammar construct '{name}' is no longer parsed"))
    for name, supported in ng["constructs"].items():
        if supported and not og["constructs"].get(name, False):
            changes.append(("additive", f"grammar construct '{name}' is now parsed"))
    for path, keys in og["conformance_samples"].items():
        new_keys = ng["conformance_samples"].get(path)
        if new_keys is None:
            changes.append(("breaking", f"conformance sample {path} removed"))
        elif any(k not in new_keys for k in keys):
            changes.append(("breaking", f"conformance sample {path}: parsed keys changed "
                            f"from {keys} to {new_keys}"))
        elif new_keys != keys:
            changes.append(("additive", f"conformance sample {path}: parsed keys extended"))
    for path in ng["conformance_samples"]:
        if path not in og["conformance_samples"]:
            changes.append(("additive", f"conformance sample {path} added"))
    return changes


def _bump_level(old: str, new: str) -> str:
    o, n = _version_tuple(old), _version_tuple(new)
    if n < o:
        return "regressed"
    if n[0] > o[0]:
        return "major"
    if n[1] > o[1]:
        return "minor"
    if n[2] > o[2]:
        return "patch"
    return "none"


def compare(baseline: dict[str, Any], current: dict[str, Any], changelog_text: str) -> list[str]:
    """Return the rule violations of ``current`` against ``baseline`` (empty means accepted).

    Rules: a breaking change needs a MAJOR bump of ``contract_version``; an additive change a
    MINOR bump; a ``grammar_version`` bump of a level needs a contract bump of at least that
    level; any surface change needs a ``Contract X.Y.Z`` line in the changelog.
    """
    violations: list[str] = []
    changes = diff_surface(baseline, current)
    required = "none"
    if any(kind == "breaking" for kind, _ in changes):
        required = "major"
    elif changes:
        required = "minor"

    grammar_level = _bump_level(baseline["grammar_version"], current["grammar_version"])
    if grammar_level == "regressed":
        violations.append(
            f"grammar_version went back from {baseline['grammar_version']} to "
            f"{current['grammar_version']}"
        )
    elif _BUMP_RANK[grammar_level] > _BUMP_RANK[required]:
        required = grammar_level

    actual = _bump_level(baseline["contract_version"], current["contract_version"])
    if actual == "regressed":
        violations.append(
            f"contract_version went back from {baseline['contract_version']} to "
            f"{current['contract_version']}"
        )
    elif _BUMP_RANK[actual] < _BUMP_RANK[required]:
        listed = "; ".join(f"[{kind}] {text}" for kind, text in changes) or "grammar version bump"
        violations.append(
            f"the surface changed ({listed}): contract_version needs a {required.upper()} bump "
            f"from {baseline['contract_version']}, found {current['contract_version']}"
        )

    if (changes or grammar_level not in ("none", "regressed")) and not re.search(
        rf"Contract {re.escape(current['contract_version'])}\b", changelog_text
    ):
        violations.append(
            f"CHANGELOG has no 'Contract {current['contract_version']}' entry for the change"
        )
    return violations


# ------------------------------------------------------------------- release tag check


def _pyproject_version(path: Path) -> str:
    """Read ``[project] version`` from a pyproject.toml (no TOML library on Python < 3.11)."""
    in_project = False
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("["):
            in_project = stripped == "[project]"
        elif in_project:
            m = re.match(r'version\s*=\s*"([^"]+)"', stripped)
            if m:
                return m[1]
    raise ContractError(f"no [project] version in {path}")


def check_tag(tag: str, pyproject: Path, package_version: str) -> list[str]:
    """Return the disagreements between a release tag and the package metadata."""
    m = re.fullmatch(r"v(\d+\.\d+\.\d+)", tag)
    if not m:
        return [f"tag '{tag}' is not a release tag of the form vX.Y.Z"]
    version = m[1]
    problems = []
    declared = _pyproject_version(pyproject)
    if declared != version:
        problems.append(f"tag {tag} != pyproject.toml version {declared}")
    if package_version != version:
        problems.append(f"tag {tag} != geneforgelang.__version__ {package_version}")
    return problems


# ------------------------------------------------------------------------------- CLI


def _git_show(ref: str, path: Path) -> str | None:
    proc = subprocess.run(
        ["git", "show", f"{ref}:{path.as_posix()}"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )
    return proc.stdout if proc.returncode == 0 else None


def _load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _cmd_check(snapshot: Path) -> int:
    live = build_contract()
    if not snapshot.is_file():
        print(f"FAIL: {snapshot} does not exist; run --write")
        return 1
    stored = _load(snapshot)
    if stored == live:
        print(f"OK: {snapshot} matches the code (contract {live['contract_version']})")
        return 0
    print(f"FAIL: {snapshot} differs from the code. Changes since the snapshot:")
    for kind, text in diff_surface(stored, live) or [("metadata", "version or text differs")]:
        print(f"  [{kind}] {text}")
    print("Bump CONTRACT_VERSION, add a 'Contract X.Y.Z' CHANGELOG line, then run --write.")
    return 1


def _cmd_against(ref: str, snapshot: Path, changelog: Path) -> int:
    old_text = _git_show(ref, snapshot)
    if old_text is None:
        print(f"NOTICE: no baseline snapshot at {ref}:{snapshot.as_posix()}; nothing to compare")
        return 0
    changelog_text = changelog.read_text(encoding="utf-8") if changelog.is_file() else ""
    violations = compare(json.loads(old_text), _load(snapshot), changelog_text)
    for v in violations:
        print(f"FAIL: {v}")
    if not violations:
        print(f"OK: {snapshot} follows the bump rules against {ref}")
    return 1 if violations else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m geneforgelang.public_contract", description=__doc__.split("\n\n")[0]
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate the snapshot")
    group.add_argument("--check", action="store_true", help="snapshot must equal the code")
    group.add_argument("--against", metavar="REF", help="apply the bump rules against a git ref")
    group.add_argument("--check-tag", metavar="TAG", help="tag must equal the package version")
    parser.add_argument("--snapshot", type=Path, default=SNAPSHOT_PATH)
    parser.add_argument("--changelog", type=Path, default=CHANGELOG_PATH)
    parser.add_argument("--pyproject", type=Path, default=Path("pyproject.toml"))
    args = parser.parse_args(argv)

    try:
        if args.write:
            args.snapshot.parent.mkdir(parents=True, exist_ok=True)
            args.snapshot.write_text(render(build_contract()), encoding="utf-8", newline="\n")
            print(f"wrote {args.snapshot}")
            return 0
        if args.check:
            return _cmd_check(args.snapshot)
        if args.against:
            return _cmd_against(args.against, args.snapshot, args.changelog)
        import geneforgelang

        problems = check_tag(args.check_tag, args.pyproject, geneforgelang.__version__)
        for p in problems:
            print(f"FAIL: {p}")
        if not problems:
            print(f"OK: {args.check_tag} matches pyproject.toml and geneforgelang.__version__")
        return 1 if problems else 0
    except ContractError as exc:
        print(f"FAIL: {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
